CREATE EXTENSION IF NOT EXISTS postgis;

DROP TABLE IF EXISTS stat_centre_urbain, centre_urbain, stat_commune,
                     commune, cercle, province_prefecture, region CASCADE;

-- ---------------------------------------------------------------------
-- REGION (16 regions - decoupage RGPH 2004)
-- ---------------------------------------------------------------------
CREATE TABLE region (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  varchar(10)  NOT NULL UNIQUE,            -- ex : '01'
    nom   varchar(100) NOT NULL,
    geom  geometry(MultiPolygon, 4326)
);

-- ---------------------------------------------------------------------
-- PROVINCE / PREFECTURE (75)
-- ---------------------------------------------------------------------
CREATE TABLE province_prefecture (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(15)  NOT NULL UNIQUE,       -- ex : '066' (code national)
    nom        varchar(100) NOT NULL,
    type       varchar(20)  NOT NULL
               CHECK (type IN ('Province', 'Préfecture')),
    region_id  integer      NOT NULL REFERENCES region(id),
    geom       geometry(MultiPolygon, 4326)
);

-- ---------------------------------------------------------------------
-- CERCLE (196 cercles + 8 prefectures d'arrondissements de Casablanca)
-- ---------------------------------------------------------------------
CREATE TABLE cercle (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    varchar(20)  NOT NULL UNIQUE,   -- ex : '01.066.03' / '09.141.01.0'
    nom                     varchar(100) NOT NULL,
    type                    varchar(40)  NOT NULL
                            CHECK (type IN ('Cercle', 'Préfecture d''arrondissements')),
    province_prefecture_id  integer      NOT NULL REFERENCES province_prefecture(id)
);

-- ---------------------------------------------------------------------
-- COMMUNE (1538 : communes rurales, municipalites, arrondissements)
-- cercle_id est NULL pour les municipalites/arrondissements hors cercle
-- ---------------------------------------------------------------------
CREATE TABLE commune (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    varchar(25)  NOT NULL UNIQUE,   -- ex : '01.066.03.05'
    nom                     varchar(150) NOT NULL,
    type                    varchar(20)  NOT NULL
                            CHECK (type IN ('Commune rurale', 'Municipalité', 'Arrondissement')),
    region_id               integer      NOT NULL REFERENCES region(id),
    province_prefecture_id  integer      NOT NULL REFERENCES province_prefecture(id),
    cercle_id               integer      NULL     REFERENCES cercle(id),
    geom                    geometry(MultiPolygon, 4326)
);

-- ---------------------------------------------------------------------
-- STAT_COMMUNE (1-1 avec commune)
-- ---------------------------------------------------------------------
CREATE TABLE stat_commune (
    id          serial  PRIMARY KEY,
    commune_id  integer NOT NULL UNIQUE REFERENCES commune(id) ON DELETE CASCADE,
    menages     integer CHECK (menages    >= 0),
    population  integer CHECK (population >= 0),
    etrangers   integer CHECK (etrangers  >= 0),
    marocains   integer CHECK (marocains  >= 0)
);

-- ---------------------------------------------------------------------
-- CENTRE_URBAIN ("Dont Centre" : centre urbain d'une commune rurale)
-- ---------------------------------------------------------------------
CREATE TABLE centre_urbain (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(30)  NOT NULL UNIQUE,       -- ex : '03.261.03.11.3'
    nom         varchar(150) NOT NULL,
    commune_id  integer      NOT NULL REFERENCES commune(id)
);

-- ---------------------------------------------------------------------
-- STAT_CENTRE_URBAIN (1-1 avec centre_urbain)
-- ---------------------------------------------------------------------
CREATE TABLE stat_centre_urbain (
    id                serial  PRIMARY KEY,
    centre_urbain_id  integer NOT NULL UNIQUE REFERENCES centre_urbain(id) ON DELETE CASCADE,
    menages           integer CHECK (menages    >= 0),
    population        integer CHECK (population >= 0),
    etrangers         integer CHECK (etrangers  >= 0),
    marocains         integer CHECK (marocains  >= 0)
);

-- ---------------------------------------------------------------------
-- Index (FK + spatiaux)
-- ---------------------------------------------------------------------
CREATE INDEX idx_province_region      ON province_prefecture (region_id);
CREATE INDEX idx_cercle_province      ON cercle (province_prefecture_id);
CREATE INDEX idx_commune_region       ON commune (region_id);
CREATE INDEX idx_commune_province     ON commune (province_prefecture_id);
CREATE INDEX idx_commune_cercle       ON commune (cercle_id);
CREATE INDEX idx_centre_commune       ON centre_urbain (commune_id);
CREATE INDEX idx_region_geom          ON region              USING gist (geom);
CREATE INDEX idx_province_geom        ON province_prefecture USING gist (geom);
CREATE INDEX idx_commune_geom         ON commune             USING gist (geom);

-- ---------------------------------------------------------------------
-- Schema de transit (staging) pour l'integration (parties II et SSIS)
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS staging;
